//! The format's JSON Schema, from the same lists the parser reads, for
//! editors' completion; `docs/reference/theme.schema.json` is generated from
//! it.

use serde_json::{Map, Value, json};

use crate::model::{MAX_RADIUS, SCHEMA_URL};
use crate::token::{ColorToken, SyntaxTag};

pub fn schema() -> Value {
    let colors: Map<String, Value> = ColorToken::ALL
        .iter()
        .map(|token| (token.as_str().to_owned(), json!({ "$ref": "#/$defs/color", "description": token.about() })))
        .collect();
    let required: Vec<&str> = ColorToken::ALL.iter().filter(|token| token.required()).map(|token| token.as_str()).collect();
    let syntax: Map<String, Value> = SyntaxTag::ALL
        .iter()
        .map(|tag| {
            let entry = json!({
                "description": tag.about(),
                "anyOf": [{ "$ref": "#/$defs/color" }, { "$ref": "#/$defs/syntaxStyle" }],
            });
            (tag.as_str().to_owned(), entry)
        })
        .collect();
    let radius = json!({ "type": "number", "minimum": 0, "maximum": MAX_RADIUS, "description": "Pixels." });
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_URL,
        "title": "Silt theme",
        "description": "A family of themes for Silt's UI. Only bg, fg-1 and accent are required in a theme; Silt derives the rest. Generated by `UPDATE_THEME_SCHEMA=1 cargo test -p silt-theme theme_schema`.",
        "type": "object",
        "required": ["name", "themes"],
        "additionalProperties": false,
        "properties": {
            "$schema": { "type": "string" },
            "name": { "type": "string", "description": "The family's name." },
            "author": { "type": "string" },
            "license": { "type": "string", "description": "An SPDX identifier, such as MIT." },
            "source": { "type": "string", "description": "Where the theme comes from, for a port." },
            "copyright": { "type": "string" },
            "themes": { "type": "array", "minItems": 1, "items": { "$ref": "#/$defs/theme" } },
        },
        "$defs": {
            "color": {
                "type": "string",
                "pattern": "^#([0-9a-fA-F]{3}|[0-9a-fA-F]{4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$",
                "description": "Hex only: #rgb, #rgba, #rrggbb or #rrggbbaa.",
            },
            "fontList": {
                "type": "array",
                "items": { "type": "string", "pattern": "^[A-Za-z0-9 _-]{1,64}$" },
                "description": "Installed fonts by name, first choice first; a generic family such as sans-serif is added if none is given.",
            },
            "syntaxStyle": {
                "type": "object",
                "additionalProperties": false,
                "properties": {
                    "color": { "$ref": "#/$defs/color" },
                    "font_style": { "enum": ["normal", "italic"] },
                    "font_weight": { "type": "number", "minimum": 100, "maximum": 900 },
                },
            },
            "theme": {
                "type": "object",
                "required": ["id", "name", "appearance", "colors"],
                "additionalProperties": false,
                "properties": {
                    "id": { "type": "string", "pattern": "^[a-z0-9][a-z0-9-]{0,63}$", "description": "Unique among your themes and Silt's; yours replaces Silt's with the same id." },
                    "name": { "type": "string" },
                    "appearance": { "enum": ["light", "dark"] },
                    "colors": { "type": "object", "required": required, "additionalProperties": false, "properties": colors },
                    "syntax": { "type": "object", "additionalProperties": false, "properties": syntax },
                    "fonts": {
                        "type": "object",
                        "additionalProperties": false,
                        "properties": { "ui": { "$ref": "#/$defs/fontList" }, "mono": { "$ref": "#/$defs/fontList" } },
                    },
                    "radii": {
                        "type": "object",
                        "additionalProperties": false,
                        "properties": { "sm": radius.clone(), "md": radius.clone(), "lg": radius },
                    },
                },
            },
        },
    })
}
